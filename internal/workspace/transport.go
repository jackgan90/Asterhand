package workspace

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/json"
	"io"
	"net"
	"net/http"
	"os"
	"strings"
	"time"
)

// Transport is a process-private file service, not the public automation API.
// Its bearer is given only to the owned adapter, never to model tool parameters.
type Transport struct {
	URL      string
	Token    string
	server   *http.Server
	service  *Service
	requests chan struct{}
}

type bridgeRequest struct {
	Action       string   `json:"action"`
	ID           string   `json:"id"`
	Run          string   `json:"run"`
	Conversation string   `json:"conversation"`
	Tool         string   `json:"tool"`
	Targets      []Target `json:"targets"`
	NewBytes     int64    `json:"new_bytes"`
	Fingerprint  string   `json:"fingerprint"`
	Path         string   `json:"path"`
	Data         []byte   `json:"data"`
	State        string   `json:"state"`
	Detail       string   `json:"detail"`
	Query        string   `json:"query"`
	Cursor       string   `json:"cursor"`
	Content      bool     `json:"content"`
	Progress     []Step   `json:"progress"`
}

func Serve(service *Service) (*Transport, error) {
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return nil, err
	}
	t := &Transport{URL: "http://" + listener.Addr().String(), Token: rand.Text(), service: service, requests: make(chan struct{}, 8)}
	t.server = &http.Server{Handler: t, ReadHeaderTimeout: 5 * time.Second, ReadTimeout: 15 * time.Second, WriteTimeout: 15 * time.Second, IdleTimeout: 15 * time.Second, MaxHeaderBytes: 4096}
	go func() { _ = t.server.Serve(listener) }()
	return t, nil
}

func (t *Transport) Close() error { return t.server.Close() }

func (t *Transport) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost || r.URL.Path != "/" || r.Header.Get("Origin") != "" || subtle.ConstantTimeCompare([]byte(r.Header.Get("Authorization")), []byte("Bearer "+t.Token)) != 1 {
		http.Error(w, "unauthorized", http.StatusUnauthorized)
		return
	}
	select {
	case t.requests <- struct{}{}:
		defer func() { <-t.requests }()
	default:
		http.Error(w, "busy", http.StatusTooManyRequests)
		return
	}
	r.Body = http.MaxBytesReader(w, r.Body, 3<<20)
	defer r.Body.Close()
	var req bridgeRequest
	decoder := json.NewDecoder(r.Body)
	decoder.DisallowUnknownFields()
	if decoder.Decode(&req) != nil || decoder.Decode(new(any)) != io.EOF {
		http.Error(w, "invalid_request", http.StatusBadRequest)
		return
	}
	value, err := t.call(req)
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	response := map[string]any{"value": value}
	if err != nil {
		code := Code(err)
		if os.IsNotExist(err) {
			code = "not_found"
		}
		response = map[string]any{"error": code}
	}
	_ = json.NewEncoder(w).Encode(response)
}

func (t *Transport) call(req bridgeRequest) (any, error) {
	s := t.service
	if req.Action == "begin" {
		s.mu.Lock()
		scope := s.scope
		turn := s.turn
		s.mu.Unlock()
		// OpenClaw canonicalizes session keys to lowercase. The binding IDs
		// are generated by the host; no model-provided identity is accepted.
		if turn == "" || req.Run != turn || !strings.EqualFold(req.Conversation, scope.Conversation) {
			return nil, fail("invalid_turn")
		}
		return s.Begin(Begin{ID: req.ID, Scope: scope, Tool: req.Tool, Targets: req.Targets, NewBytes: req.NewBytes, Fingerprint: req.Fingerprint, Progress: req.Progress})
	}
	switch req.Action {
	case "end":
		return s.End(req.ID, req.State, req.Detail)
	case "read":
		if req.ID != "" {
			return s.NativeRead(req.ID, req.Path)
		}
		// Bootstrap and keyword indexing use only safe, bounded workspace reads.
		return s.readAll(req.Path)
	case "stat":
		return s.Stat(req.Path)
	case "list":
		return s.ReadDirectory(req.Path)
	case "search":
		return s.Search(req.Path, req.Query, req.Cursor, req.Content, true)
	case "write":
		return s.Write(req.ID, req.Path, req.Data, false)
	case "create":
		return s.Write(req.ID, req.Path, req.Data, true)
	case "remove":
		return nil, s.Remove(req.ID, req.Path)
	case "mkdir":
		// The native algorithm may request mkdir before write. Admit only a
		// declared parent; actual creation stays inside the protected write.
		s.mu.Lock()
		defer s.mu.Unlock()
		name, err := relative(req.Path, true)
		if err != nil {
			return nil, err
		}
		if s.active == nil || s.active.op.ID != req.ID {
			return nil, fail("invalid_call")
		}
		if name == "" {
			return nil, nil
		}
		for _, target := range s.active.op.Changes {
			if strings.HasPrefix(pathKey(target.Path), pathKey(name)+"/") {
				return nil, nil
			}
		}
		return nil, fail("undeclared_target")
	default:
		return nil, fail("unsupported")
	}
}

func (s *Service) readAll(name string) ([]byte, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if !s.enabled {
		return nil, fail("not_authorized")
	}
	name, err := relative(name, false)
	if err != nil {
		return nil, err
	}
	h, cleanup, err := s.readHandle(name)
	if err != nil {
		return nil, err
	}
	defer cleanup()
	return h.bytes(MaxFileBytes)
}
