// Generate fixed-width lookup data from the reviewed WHATWG source snapshot.
// Downloaded source files stay outside the repository; every input is pinned.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/generate-log-encoding.mjs SOURCE_DIRECTORY [--check]');
const expected = {
  'index-gb18030.txt': '746b3c55f1a8ec4b90b451f384437a17fd37cd51cd668456a28071a758d10784',
  'index-gb18030-ranges.txt': '874c6b6f6f74cf7d427ad228d5b41ddd9354fffd92a2259bf429f86e6baa7a1e',
  'index-big5.txt': '08e24270c8e95d998c994c03f907e972480dc01f58743e078654cc466203c8ff',
  LICENSE: '85dc6f5ccb57a6fe8c33d158f9fc8fc7ee5655a5d3db2cdd131c6a3d0f48a864',
};
const destination = path.join(root, 'internal/localcommands/encodingdata');
const tables = {};
await fs.mkdir(destination, {recursive: true});
for (const [name, digest] of Object.entries(expected)) {
  const input = await fs.readFile(path.join(source, name));
  if (crypto.createHash('sha256').update(input).digest('hex') !== digest) throw new Error(`Input checksum mismatch: ${name}`);
  let output = input, filename = 'LICENSE';
  if (name !== 'LICENSE') {
    const entries = input.toString('utf8').split(/\r?\n/).filter(line => /^\s*\d+\s+0x/u.test(line))
      .map(line => { const [pointer, code] = line.trim().split(/\s+/u); return [Number(pointer), Number(code)]; });
    const ranges = name.includes('-ranges');
    output = Buffer.alloc(ranges ? entries.length * 8 : (entries.at(-1)[0] + 1) * 4);
    entries.forEach(([pointer, code], index) => {
      if (ranges) { output.writeUInt32LE(pointer, index * 8); output.writeUInt32LE(code, index * 8 + 4); }
      else output.writeUInt32LE(code, pointer * 4);
    });
    filename = name.replace('.txt', '.bin');
  }
  const target = path.join(destination, filename);
  if (filename.endsWith('.bin')) tables[filename] = output.toString('base64');
  if (process.argv.includes('--check')) {
    if (!(await fs.readFile(target)).equals(output)) throw new Error(`Generated data differs: ${filename}`);
  } else await fs.writeFile(target, output);
  console.log(`${filename}: ${output.length} bytes, sha256 ${crypto.createHash('sha256').update(output).digest('hex')}`);
}
const moduleText = '// Generated by scripts/generate-log-encoding.mjs; DO NOT EDIT.\n// WHATWG BSD-3-Clause: internal/localcommands/encodingdata/LICENSE.\nexport const legacyLogTables = '+JSON.stringify(tables)+';\n';
const modulePath = path.join(root, 'internal/quickinput/assets/legacy-log-tables.mjs');
if (process.argv.includes('--check')) {
  if (await fs.readFile(modulePath, 'utf8') !== moduleText) throw new Error('Generated browser tables differ');
} else await fs.writeFile(modulePath, moduleText);
