import {readFile, readdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const defaultRepoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cjkPattern = /[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3000-\u303f\uff00-\uffef]/;
const placeholderPattern = /\{([a-zA-Z0-9_]+)\}/g;

export function extractPlaceholders(text) {
  const names = new Set();
  for (const match of String(text).matchAll(placeholderPattern)) names.add(match[1]);
  return [...names].sort();
}

export function validateCatalogs(manifest, catalogs) {
  const errors = [];
  if (!manifest || manifest.schema !== 1) errors.push('manifest.json schema must be 1');
  if (!Array.isArray(manifest?.locales) || manifest.locales.length === 0) {
    errors.push('manifest.json must declare at least one locale');
    return errors;
  }
  const seenIds = new Set();
  for (const entry of manifest.locales) {
    if (!entry?.id || typeof entry.id !== 'string') errors.push('locale entry missing string id');
    else if (seenIds.has(entry.id)) errors.push(`duplicate locale id: ${entry.id}`);
    else seenIds.add(entry.id);
    if (!entry?.label || typeof entry.label !== 'string') errors.push(`locale ${entry?.id}: missing label`);
    if (!entry?.html_lang || typeof entry.html_lang !== 'string') errors.push(`locale ${entry?.id}: missing html_lang`);
    if (!Array.isArray(entry?.prefixes) || entry.prefixes.length === 0) errors.push(`locale ${entry?.id}: missing prefixes`);
  }
  if (!seenIds.has(manifest.default_fallback)) {
    errors.push(`default_fallback ${manifest.default_fallback} is not registered in locales`);
  }
  const baselineId = manifest.locales[0].id;
  const baseline = catalogs[baselineId];
  if (!baseline || typeof baseline !== 'object') {
    errors.push(`missing catalog for ${baselineId}`);
    return errors;
  }
  const baselineKeys = Object.keys(baseline).sort();
  if (baselineKeys.length === 0) errors.push(`catalog ${baselineId} cannot be empty`);

  for (const entry of manifest.locales) {
    const cat = catalogs[entry.id];
    if (!cat || typeof cat !== 'object') {
      errors.push(`missing catalog for ${entry.id}`);
      continue;
    }
    const keys = Object.keys(cat).sort();
    for (const k of baselineKeys) {
      if (!(k in cat)) errors.push(`locale ${entry.id} missing key: ${k}`);
    }
    for (const k of keys) {
      if (!(k in baseline)) errors.push(`locale ${entry.id} has extra key not in ${baselineId}: ${k}`);
      const val = cat[k];
      if (typeof val !== 'string' || val.length === 0) {
        errors.push(`locale ${entry.id} key ${k} must be a non-empty string`);
        continue;
      }
      if (entry.disallow_cjk && cjkPattern.test(val)) {
        errors.push(`locale ${entry.id} (disallow_cjk) contains CJK characters in key ${k}: ${val}`);
      }
      if (k in baseline && typeof baseline[k] === 'string') {
        const expectedParams = extractPlaceholders(baseline[k]).join(',');
        const actualParams = extractPlaceholders(val).join(',');
        if (expectedParams !== actualParams) {
          errors.push(`placeholder mismatch in ${entry.id} key ${k}: expected {${expectedParams}}, got {${actualParams}}`);
        }
      }
    }
  }
  return errors;
}

export function renderCatalogModule(manifest, catalogs, prefixes) {
  const localeMeta = manifest.locales.map((entry) => ({
    id: entry.id,
    label: entry.label,
    htmlLang: entry.html_lang,
    prefixes: entry.prefixes,
    showBrandSubtitle: Boolean(entry.show_brand_subtitle),
  }));
  const filtered = {};
  for (const entry of manifest.locales) {
    const src = catalogs[entry.id] || {};
    const out = {};
    for (const key of Object.keys(src).sort()) {
      if (prefixes.some((prefix) => key.startsWith(prefix))) out[key] = src[key];
    }
    filtered[entry.id] = out;
  }
  return (
    '// Code generated by scripts/sync-i18n.mjs; DO NOT EDIT.\n' +
    `export const defaultFallback = ${JSON.stringify(manifest.default_fallback)};\n` +
    `export const locales = Object.freeze(${JSON.stringify(localeMeta, null, 2)});\n` +
    `export const catalog = Object.freeze(${JSON.stringify(filtered, null, 2)});\n`
  );
}

export async function loadLocaleBundle(localesDir) {
  const manifest = JSON.parse(await readFile(path.join(localesDir, 'manifest.json'), 'utf8'));
  const catalogs = {};
  for (const entry of manifest.locales || []) {
    const raw = await readFile(path.join(localesDir, `${entry.id}.json`), 'utf8');
    catalogs[entry.id] = JSON.parse(raw);
  }
  return {manifest, catalogs};
}

export async function syncCatalogModules(repoRoot = defaultRepoRoot, {write = true} = {}) {
  const localesDir = path.join(repoRoot, 'internal', 'i18n', 'locales');
  const {manifest, catalogs} = await loadLocaleBundle(localesDir);
  const errors = validateCatalogs(manifest, catalogs);
  if (errors.length > 0) throw new Error('i18n catalog validation failed:\n' + errors.join('\n'));

  const targets = [
    {file: path.join(repoRoot, 'web', 'i18n-catalog.mjs'), prefixes: manifest.web_prefixes},
    {file: path.join(repoRoot, 'internal', 'quickinput', 'assets', 'i18n-catalog.mjs'), prefixes: manifest.quickinput_prefixes},
  ];
  for (const target of targets) {
    const expected = renderCatalogModule(manifest, catalogs, target.prefixes);
    if (write) {
      await writeFile(target.file, expected, 'utf8');
    } else {
      let actual = '';
      try {
        actual = await readFile(target.file, 'utf8');
      } catch {
        errors.push(`generated catalog missing: ${path.relative(repoRoot, target.file).replaceAll('\\', '/')}`);
        continue;
      }
      if (actual !== expected) {
        errors.push(`generated catalog out of date: ${path.relative(repoRoot, target.file).replaceAll('\\', '/')} (run node scripts/sync-i18n.mjs)`);
      }
    }
  }
  return {manifest, catalogs, errors};
}

function parseAttributes(attrText) {
  const attrs = new Map();
  const re = /([a-zA-Z0-9_:-]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?/g;
  for (const m of attrText.matchAll(re)) {
    attrs.set(m[1].toLowerCase(), m[2] ?? m[3] ?? m[4] ?? '');
  }
  return attrs;
}

export function checkHtmlTemplate(relPath, html, allowedLiterals, validKeys) {
  const errors = [];
  const referencedKeys = new Set();
  const allowed = new Set(allowedLiterals);
  const cleaned = html
    .replace(/<!doctype\b[^>]*>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '');

  const voidTags = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr']);
  const stack = [];
  const tokenRe = /<\/?([a-zA-Z0-9-]+)([^>]*)>|([^<]+)/g;
  for (const match of cleaned.matchAll(tokenRe)) {
    if (match[3] !== undefined) {
      const text = match[3].replace(/\s+/g, ' ').trim();
      if (!text || allowed.has(text)) continue;
      const top = stack[stack.length - 1];
      if (!top || !top.attrs.has('data-i18n')) {
        errors.push(`${relPath}: unbound HTML text "${text}" in <${top?.tag || 'root'}>`);
      }
      continue;
    }
    const raw = match[0];
    const tag = match[1].toLowerCase();
    if (raw.startsWith('</')) {
      while (stack.length > 0) {
        const popped = stack.pop();
        if (popped.tag === tag) break;
      }
      continue;
    }
    const attrs = parseAttributes(match[2] || '');
    for (const [attrName, i18nAttr] of [
      ['placeholder', 'data-i18n-placeholder'],
      ['aria-label', 'data-i18n-aria-label'],
      ['title', 'data-i18n-title'],
    ]) {
      const val = (attrs.get(attrName) || '').trim();
      if (val && !allowed.has(val) && !attrs.has(i18nAttr)) {
        errors.push(`${relPath}: <${tag}> ${attrName}="${val}" missing ${i18nAttr}`);
      }
    }
    for (const i18nAttr of ['data-i18n', 'data-i18n-placeholder', 'data-i18n-aria-label', 'data-i18n-title']) {
      if (attrs.has(i18nAttr)) {
        const key = attrs.get(i18nAttr);
        referencedKeys.add(key);
        if (!validKeys.has(key)) errors.push(`${relPath}: unknown i18n key "${key}" in ${i18nAttr}`);
      }
    }
    const selfClosing = raw.endsWith('/>') || voidTags.has(tag);
    if (!selfClosing) stack.push({tag, attrs});
  }
  return {errors, referencedKeys};
}

export function scanJsLiteralsAndComments(source) {
  const literals = [];
  let stripped = '';
  let i = 0;
  let line = 1;
  let prevSig = '';

  const canStartRegex = () =>
    !prevSig || ['(', ',', '=', ':', '[', '!', '&', '|', '?', '{', '}', ';', '+', '-', '*', '%', '~', '^', '<', '>'].includes(prevSig) ||
    ['return', 'throw', 'case', 'in', 'of', 'typeof', 'void', 'delete', 'await', 'yield'].includes(prevSig);

  while (i < source.length) {
    const ch = source[i];
    const next = source[i + 1];
    if (ch === '\n') {
      line++;
      stripped += '\n';
      i++;
      continue;
    }
    if (ch === '/' && next === '/') {
      while (i < source.length && source[i] !== '\n') i++;
      continue;
    }
    if (ch === '/' && next === '*') {
      i += 2;
      while (i < source.length && !(source[i] === '*' && source[i + 1] === '/')) {
        if (source[i] === '\n') {
          line++;
          stripped += '\n';
        }
        i++;
      }
      i += 2;
      stripped += ' ';
      continue;
    }
    if (ch === '/' && canStartRegex()) {
      let j = i + 1;
      let inClass = false;
      let ok = true;
      while (j < source.length) {
        const c = source[j];
        if (c === '\n') { ok = false; break; }
        if (c === '\\') { j += 2; continue; }
        if (c === '[') inClass = true;
        else if (c === ']') inClass = false;
        else if (c === '/' && !inClass) break;
        j++;
      }
      if (ok && j < source.length && source[j] === '/') {
        j++;
        while (j < source.length && /[a-z]/i.test(source[j])) j++;
        stripped += ' /re/ ';
        prevSig = '/re/';
        i = j;
        continue;
      }
    }
    if (ch === "'" || ch === '"' || ch === '`') {
      const quote = ch;
      const startLine = line;
      let value = '';
      i++;
      while (i < source.length && source[i] !== quote) {
        if (source[i] === '\\') {
          value += source.slice(i, i + 2);
          if (source[i + 1] === '\n') line++;
          i += 2;
          continue;
        }
        if (quote === '`' && source[i] === '$' && source[i + 1] === '{') {
          value += '${';
          i += 2;
          let depth = 1;
          while (i < source.length && depth > 0) {
            if (source[i] === '\n') line++;
            if (source[i] === '{') depth++;
            else if (source[i] === '}') depth--;
            if (depth > 0) value += source[i];
            i++;
          }
          value += '}';
          continue;
        }
        if (source[i] === '\n') line++;
        value += source[i++];
      }
      i++;
      literals.push({line: startLine, quote, value});
      stripped += `${quote}${value.replace(/\n/g, ' ')}${quote}`;
      prevSig = 'str';
      continue;
    }
    stripped += ch;
    if (!/\s/.test(ch)) {
      if (/[a-zA-Z0-9_$]/.test(ch)) {
        let word = ch;
        let k = i + 1;
        while (k < source.length && /[a-zA-Z0-9_$]/.test(source[k])) word += source[k++];
        prevSig = word;
        stripped += word.slice(1);
        i = k;
        continue;
      }
      prevSig = ch;
    }
    i++;
  }
  return {literals, stripped};
}

const keyPrefixPattern = /^(common|brand|web|quickinput|desktop|status|err)\.[a-z0-9_.]+$/;

const defaultJsUiSinks = Object.freeze([
  {kind: 'property', name: 'textContent'},
  {kind: 'property', name: 'innerText'},
  {kind: 'call', name: 'node', arg_indices: [1]},
  {kind: 'call', name: 'element', arg_indices: [1]},
  {kind: 'call', name: 'confirm', arg_indices: [0]},
  {kind: 'call', name: 'prompt', arg_indices: [0]},
  {kind: 'call', name: 'notice', arg_indices: [0]},
  {kind: 'call', name: 'say', arg_indices: [0]},
  {kind: 'attribute_call', name: 'setAttribute', attributes: ['aria-label', 'title', 'placeholder']},
]);

function escapeRegex(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function stripTemplateInterpolations(value) {
  let out = '';
  let i = 0;
  while (i < value.length) {
    if (value[i] === '$' && value[i + 1] === '{') {
      i += 2;
      let depth = 1;
      while (i < value.length && depth > 0) {
        if (value[i] === '{') depth++;
        else if (value[i] === '}') depth--;
        i++;
      }
      out += ' ';
      continue;
    }
    out += value[i++];
  }
  return out;
}

function isNaturalEnglishUiLiteral(value) {
  const cleaned = stripTemplateInterpolations(value).trim();
  if (!cleaned) return false;
  if (/^(Ctrl|Alt|Shift|Space|Enter|Pause|Insert|Delete|Home|End|PageUp|PageDown|Key|Digit|F\d+|SHA-256:|0x|%s)$/i.test(cleaned)) return false;
  return /[A-Za-z]{2,}/.test(cleaned);
}

function normalizeJsSinkRule(raw) {
  if (typeof raw === 'string' && raw.trim()) {
    return {kind: 'call', name: raw.trim(), arg_indices: [0]};
  }
  if (!raw || typeof raw !== 'object' || typeof raw.name !== 'string' || !raw.name.trim()) {
    throw new Error(`invalid js_ui_sinks rule: ${JSON.stringify(raw)}`);
  }
  if (raw.kind === 'property') return {kind: 'property', name: raw.name.trim()};
  if (raw.kind === 'call') {
    const indices = Array.isArray(raw.arg_indices) && raw.arg_indices.length ? raw.arg_indices : [0];
    return {kind: 'call', name: raw.name.trim(), arg_indices: indices};
  }
  if (raw.kind === 'attribute_call') {
    if (!Array.isArray(raw.attributes) || raw.attributes.length === 0) {
      throw new Error(`attribute_call sink "${raw.name}" requires non-empty attributes`);
    }
    return {kind: 'attribute_call', name: raw.name.trim(), attributes: raw.attributes.map((a) => String(a).toLowerCase())};
  }
  throw new Error(`unsupported js_ui_sinks kind "${raw.kind}"`);
}

function extractCallArgs(text, openParenIndex) {
  const args = [];
  let current = '';
  let depth = 1;
  let i = openParenIndex + 1;
  while (i < text.length && depth > 0) {
    const ch = text[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      const quote = ch;
      current += ch;
      i++;
      while (i < text.length && text[i] !== quote) {
        if (text[i] === '\\') {
          current += text.slice(i, i + 2);
          i += 2;
          continue;
        }
        current += text[i++];
      }
      if (i < text.length) current += text[i++];
      continue;
    }
    if (ch === '(' || ch === '[' || ch === '{') {
      depth++;
      current += ch;
    } else if (ch === ')' || ch === ']' || ch === '}') {
      depth--;
      if (depth === 0) {
        if (current.trim() || args.length > 0) args.push(current.trim());
        return args;
      }
      current += ch;
    } else if (ch === ',' && depth === 1) {
      args.push(current.trim());
      current = '';
    } else {
      current += ch;
    }
    i++;
  }
  return args;
}

function unquoteSingleLiteral(expr, {allowInterpolation = false} = {}) {
  const trimmed = String(expr || '').trim();
  const match = trimmed.match(/^(['"`])((?:\\.|(?!\1).)*)\1$/s);
  if (!match) return null;
  if (!allowInterpolation && match[1] === '`' && match[2].includes('${')) return null;
  return match[2];
}

function collectObjectStringMaps(stripped) {
  const maps = new Map();
  const declRe = /\b(?:const|let|var)\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*=\s*(?:Object\.freeze\s*\(\s*)?\{/g;
  for (const m of stripped.matchAll(declRe)) {
    const name = m[1];
    const openBrace = stripped.indexOf('{', m.index + m[0].length - 1);
    let depth = 1;
    let body = '';
    let i = openBrace + 1;
    while (i < stripped.length && depth > 0) {
      const ch = stripped[i];
      if (ch === "'" || ch === '"' || ch === '`') {
        const quote = ch;
        body += ch;
        i++;
        while (i < stripped.length && stripped[i] !== quote) {
          if (stripped[i] === '\\') { body += stripped.slice(i, i + 2); i += 2; continue; }
          body += stripped[i++];
        }
        if (i < stripped.length) body += stripped[i++];
        continue;
      }
      if (ch === '{') depth++;
      else if (ch === '}') { depth--; if (depth === 0) break; }
      if (depth === 1) body += ch;
      i++;
    }
    const values = [];
    for (const prop of body.matchAll(/(?:[A-Za-z0-9_$]+|['"][^'"]+['"])\s*:\s*(['"`])((?:\\.|(?!\1).)*)\1/g)) {
      if (prop[1] === '`' && prop[2].includes('${')) continue;
      if (prop[2]) values.push(prop[2]);
    }
    if (values.length > 0) maps.set(name, values);
  }
  return maps;
}

function checkJsSinkRule(relPath, stripped, validKeys, sink, errors) {
  if (sink.kind === 'property') {
    const propRe = new RegExp(`\\.\\s*${escapeRegex(sink.name)}\\s*\\+?=\\s*(['"\`])((?:\\\\.|(?!\\1).)*)\\1`, 'g');
    for (const m of stripped.matchAll(propRe)) {
      if (!validKeys.has(m[2]) && isNaturalEnglishUiLiteral(m[2])) {
        errors.push(`${relPath}: direct natural-language UI literal "${m[2]}" in .${sink.name}`);
      }
    }
    return;
  }
  const callRe = sink.kind === 'attribute_call'
    ? new RegExp(`\\.\\s*${escapeRegex(sink.name)}\\s*\\(`, 'g')
    : new RegExp(`\\b${escapeRegex(sink.name)}\\s*\\(`, 'g');
  for (const m of stripped.matchAll(callRe)) {
    const openIdx = m.index + m[0].length - 1;
    const args = extractCallArgs(stripped, openIdx);
    if (sink.kind === 'attribute_call') {
      const attrName = unquoteSingleLiteral(args[0])?.toLowerCase();
      const attrVal = unquoteSingleLiteral(args[1], {allowInterpolation: true});
      if (attrName && sink.attributes.includes(attrName) && attrVal !== null && !validKeys.has(attrVal) && isNaturalEnglishUiLiteral(attrVal)) {
        errors.push(`${relPath}: direct natural-language UI literal "${attrVal}" in .${sink.name}("${attrName}", ...)`);
      }
      continue;
    }
    for (const idx of sink.arg_indices) {
      const val = unquoteSingleLiteral(args[idx], {allowInterpolation: true});
      if (val !== null && !validKeys.has(val) && isNaturalEnglishUiLiteral(val)) {
        errors.push(`${relPath}: direct natural-language UI literal "${val}" in ${sink.name}(...)`);
      }
    }
  }
}

export function checkJsSource(relPath, source, validKeys, jsUiSinks = defaultJsUiSinks) {
  const errors = [];
  const referencedKeys = new Set();
  const normalizedSinks = jsUiSinks.map(normalizeJsSinkRule);
  const {literals, stripped} = scanJsLiteralsAndComments(source);
  const objectMaps = collectObjectStringMaps(stripped);

  for (const lit of literals) {
    if (cjkPattern.test(lit.value)) {
      errors.push(`${relPath}:${lit.line}: hardcoded CJK string literal ${lit.quote}${lit.value}${lit.quote}`);
    }
    if (keyPrefixPattern.test(lit.value)) {
      referencedKeys.add(lit.value);
      if (!validKeys.has(lit.value)) {
        errors.push(`${relPath}:${lit.line}: unknown i18n key literal "${lit.value}"`);
      }
    }
  }

  for (const m of stripped.matchAll(/\b(t|qt|localizeMessage)\s*\(/g)) {
    const args = extractCallArgs(stripped, m.index + m[0].length - 1);
    const directKey = unquoteSingleLiteral(args[0]);
    if (directKey !== null) {
      referencedKeys.add(directKey);
      if (!validKeys.has(directKey)) {
        errors.push(`${relPath}: unknown i18n key "${directKey}" in ${m[1]}(...)`);
      }
      continue;
    }
    const argExpr = args[0] || '';
    for (const [mapName, mapValues] of objectMaps) {
      if (new RegExp(`\\b${escapeRegex(mapName)}\\s*(?:\\.|\\[)`).test(argExpr)) {
        for (const mapVal of mapValues) {
          referencedKeys.add(mapVal);
          if (!validKeys.has(mapVal)) {
            errors.push(`${relPath}: unknown i18n key "${mapVal}" in map "${mapName}" passed to ${m[1]}(...)`);
          }
        }
      }
    }
  }

  for (const m of stripped.matchAll(/\bfailure\s*\(/g)) {
    const args = extractCallArgs(stripped, m.index + m[0].length - 1);
    const key = unquoteSingleLiteral(args[1]);
    if (key !== null) {
      referencedKeys.add(key);
      if (!validKeys.has(key)) {
        errors.push(`${relPath}: unknown i18n key "${key}" in failure(...)`);
      }
    }
  }

  for (const sink of normalizedSinks) {
    checkJsSinkRule(relPath, stripped, validKeys, sink, errors);
  }
  return {errors, referencedKeys};
}

async function listSourceFiles(dir, exts) {
  const out = [];
  const entries = await readdir(dir, {withFileTypes: true});
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...(await listSourceFiles(full, exts)));
    } else if (exts.some((ext) => entry.name.endsWith(ext))) {
      out.push(full);
    }
  }
  return out.sort();
}

export async function checkFrontendI18n(repoRoot = defaultRepoRoot) {
  const rules = JSON.parse(await readFile(path.join(repoRoot, 'internal', 'i18n', 'guard-rules.json'), 'utf8'));
  if (!Array.isArray(rules.js_ui_sinks) || rules.js_ui_sinks.length === 0) {
    throw new Error('guard-rules.json must declare non-empty js_ui_sinks');
  }
  const {manifest, catalogs, errors} = await syncCatalogModules(repoRoot, {write: false});
  const allKeys = new Set(Object.keys(catalogs[manifest.locales[0].id] || {}));
  const webKeys = new Set([...allKeys].filter((k) => manifest.web_prefixes.some((p) => k.startsWith(p))));
  const quickKeys = new Set([...allKeys].filter((k) => manifest.quickinput_prefixes.some((p) => k.startsWith(p))));
  const referencedKeys = new Set();

  for (const htmlRel of rules.html_checked_files) {
    const html = await readFile(path.join(repoRoot, htmlRel), 'utf8');
    const valid = htmlRel.startsWith('web/') ? webKeys : quickKeys;
    const res = checkHtmlTemplate(htmlRel, html, rules.html_allowed_literals, valid);
    errors.push(...res.errors);
    for (const k of res.referencedKeys) referencedKeys.add(k);
  }

  for (const dirRel of rules.js_checked_dirs) {
    const files = await listSourceFiles(path.join(repoRoot, dirRel), ['.js', '.mjs']);
    for (const full of files) {
      const rel = path.relative(repoRoot, full).replaceAll('\\', '/');
      if (rules.excluded_paths.some((ex) => rel === ex || rel.startsWith(ex))) continue;
      const source = await readFile(full, 'utf8');
      const valid = rel.startsWith('web/') ? webKeys : rel.startsWith('internal/quickinput/') ? quickKeys : allKeys;
      const res = checkJsSource(rel, source, valid, rules.js_ui_sinks);
      errors.push(...res.errors);
      for (const k of res.referencedKeys) referencedKeys.add(k);
    }
  }
  return {errors, referencedKeys, manifest, catalogs};
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    const {errors} = await checkFrontendI18n(defaultRepoRoot);
    if (errors.length > 0) {
      console.error(errors.join('\n'));
      process.exit(1);
    }
    console.log('i18n catalog and frontend guardrails verified.');
  } else {
    await syncCatalogModules(defaultRepoRoot, {write: true});
    console.log('Generated web/i18n-catalog.mjs and internal/quickinput/assets/i18n-catalog.mjs');
  }
}
